"""
Post-analysis and article-ready plots for leakage-free radiomics modeling runs.

Reads multiple modeling run folders generated by modeling.py and produces:
- merged results table
- compact summary CSVs
- a small set of publication-oriented plots
- ranking tables focused on Axis A (NR / RS / VS / FK)

Expected structure:
<modelado_dir>/
    common_neutral_24arms/
        results_models.csv
        run_config.json
    per_arm_ensemble_24arms/
        results_models.csv
        run_config.json
    full_features_24arms/
        results_models.csv
        run_config.json
    common_vs_24arms/
        results_models.csv
        run_config.json
    per_arm_mwu_24arms/
        results_models.csv
        run_config.json
    ...

Main design principles:
- Avoid producing too many figures
- Focus on the most paper-relevant comparisons
- Put Axis A first, then feature mode / model / ComBat
- Save all intermediate summary tables as CSV
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Dict, List, Optional

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt


# =============================================================================
# CONFIG
# =============================================================================
AXIS_A_ORDER = ["NR", "RS", "VS", "FK"]
MODEL_ORDER = ["LR", "XGB", "MLP"]
FEATURE_MODE_ORDER = [
    "COMMON_NEUTRAL",
    "COMMON_VS",
    "PER_ARM_ENSEMBLE",
    "PER_ARM_MWU",
    "FULL_FEATURES",
]

DEFAULT_RUNS = [
    "common_neutral_24arms",
    "per_arm_ensemble_24arms",
    "full_features_24arms",
    "common_vs_24arms",
    "per_arm_mwu_24arms",
    "common_neutral_24arms_mlp",
    "full_features_24arms_mlp",
    "per_arm_ensemble_24arms_mlp",
]


# =============================================================================
# HELPERS
# =============================================================================
def ensure_dir(path: Path) -> None:
    path.mkdir(parents=True, exist_ok=True)


def ordered_unique(values: List[str], preferred_order: List[str]) -> List[str]:
    values = [v for v in values if pd.notna(v)]
    out = [v for v in preferred_order if v in values]
    out += [v for v in values if v not in out]
    return out


def safe_read_json(path: Path) -> Dict:
    if not path.exists():
        return {}
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)


def add_run_metadata(df: pd.DataFrame, run_name: str, run_cfg: Dict) -> pd.DataFrame:
    df = df.copy()
    df["run_name"] = run_name
    df["analysis_label"] = run_cfg.get("analysis_label", run_name)
    df["feature_mode_from_cfg"] = run_cfg.get("feature_mode", np.nan)
    df["include_mlp_from_cfg"] = run_cfg.get("include_mlp", np.nan)
    df["drop_shape_from_cfg"] = run_cfg.get("drop_shape", np.nan)
    df["batch_mode_from_cfg"] = run_cfg.get("batch_mode", np.nan)
    return df


def load_one_run(run_dir: Path) -> Optional[pd.DataFrame]:
    results_csv = run_dir / "results_models.csv"
    if not results_csv.exists():
        print(f"[WARN] Missing results_models.csv in: {run_dir}")
        return None

    try:
        df = pd.read_csv(results_csv)
    except Exception as e:
        print(f"[WARN] Could not read {results_csv}: {e}")
        return None

    cfg = safe_read_json(run_dir / "run_config.json")
    df = add_run_metadata(df, run_dir.name, cfg)

    # Harmonize columns if older runs differ slightly
    if "feature_mode" not in df.columns:
        df["feature_mode"] = df["feature_mode_from_cfg"]
    if "model" in df.columns:
        df["model"] = df["model"].astype(str)

    return df


def load_all_runs(modelado_dir: Path, run_names: List[str]) -> pd.DataFrame:
    dfs = []
    for run_name in run_names:
        run_dir = modelado_dir / run_name
        if not run_dir.exists():
            print(f"[WARN] Run folder not found: {run_dir}")
            continue
        df = load_one_run(run_dir)
        if df is not None and len(df) > 0:
            dfs.append(df)

    if not dfs:
        raise FileNotFoundError("No valid run folders with results_models.csv were found.")

    out = pd.concat(dfs, axis=0, ignore_index=True)

    # Coerce key numeric columns
    numeric_cols = [
        "test_auc", "cv_auc_mean", "cv_auc_std", "train_auc",
        "test_ap", "test_brier", "test_ece",
        "test_acc", "test_sens", "test_spec",
        "generalization_gap_cv_test_auc",
        "overfit_gap_train_test_auc",
        "n_features",
    ]
    for c in numeric_cols:
        if c in out.columns:
            out[c] = pd.to_numeric(out[c], errors="coerce")

    return out


def filter_core_axis_a(df: pd.DataFrame) -> pd.DataFrame:
    """
    Main clean subset for paper-facing comparisons:
    prioritize C=OFF and no_density block when available.
    """
    df = df.copy()
    keep = (
        (df["C"] == "OFF") &
        (df["B"] == "OFF") &
        (df["N"] == "OFF")
    )
    sub = df.loc[keep].copy()
    if len(sub) == 0:
        return df.copy()
    return sub


def summarize_group(
    df: pd.DataFrame,
    group_cols: List[str],
    metric_cols: List[str],
) -> pd.DataFrame:
    agg = {}
    for m in metric_cols:
        agg[m] = ["mean", "std", "median", "min", "max", "count"]

    out = df.groupby(group_cols).agg(agg)
    out.columns = ["_".join(col).strip() for col in out.columns.to_flat_index()]
    out = out.reset_index()
    return out


def save_csv(df: pd.DataFrame, path: Path) -> None:
    df.to_csv(path, index=False)


def boxplot_by_category(
    df: pd.DataFrame,
    category_col: str,
    value_col: str,
    title: str,
    ylabel: str,
    out_path: Path,
    order: Optional[List[str]] = None,
    figsize=(8, 5),
) -> None:
    data = df.copy()
    data = data[[category_col, value_col]].dropna()
    if data.empty:
        print(f"[WARN] No data for plot: {title}")
        return

    if order is None:
        order = list(data[category_col].dropna().unique())

    plot_groups = []
    labels = []
    for cat in order:
        vals = data.loc[data[category_col] == cat, value_col].dropna().values
        if len(vals) > 0:
            plot_groups.append(vals)
            labels.append(cat)

    if len(plot_groups) == 0:
        print(f"[WARN] No valid grouped data for plot: {title}")
        return

    plt.figure(figsize=figsize)
    plt.boxplot(plot_groups, labels=labels, showfliers=False)
    plt.title(title)
    plt.ylabel(ylabel)
    plt.tight_layout()
    plt.savefig(out_path, dpi=300, bbox_inches="tight")
    plt.close()


def barplot_mean_with_error(
    df: pd.DataFrame,
    category_col: str,
    value_col: str,
    title: str,
    ylabel: str,
    out_path: Path,
    order: Optional[List[str]] = None,
    figsize=(8, 5),
) -> None:
    data = df[[category_col, value_col]].dropna().copy()
    if data.empty:
        print(f"[WARN] No data for plot: {title}")
        return

    g = data.groupby(category_col)[value_col].agg(["mean", "std", "count"]).reset_index()
    if order is None:
        order = list(g[category_col].unique())
    g[category_col] = pd.Categorical(g[category_col], categories=order, ordered=True)
    g = g.sort_values(category_col)

    plt.figure(figsize=figsize)
    plt.bar(g[category_col].astype(str), g["mean"], yerr=g["std"].fillna(0.0), capsize=4)
    plt.title(title)
    plt.ylabel(ylabel)
    plt.tight_layout()
    plt.savefig(out_path, dpi=300, bbox_inches="tight")
    plt.close()


def make_top_table(
    df: pd.DataFrame,
    sort_cols: List[str],
    ascending: List[bool],
    top_n: int = 20,
) -> pd.DataFrame:
    out = df.sort_values(sort_cols, ascending=ascending).head(top_n).copy()
    return out.reset_index(drop=True)


# =============================================================================
# MAIN PLOTS
# =============================================================================
def generate_core_plots(all_df: pd.DataFrame, outdir: Path) -> None:
    figs_dir = outdir / "figures"
    tables_dir = outdir / "tables"
    ensure_dir(figs_dir)
    ensure_dir(tables_dir)

    # Save merged raw table
    save_csv(all_df, outdir / "all_runs_merged_results.csv")

    # -------------------------------------------------------------------------
    # 1) Main Axis A subset: OFF / OFF / OFF
    # -------------------------------------------------------------------------
    axis_a_df = filter_core_axis_a(all_df)
    save_csv(axis_a_df, tables_dir / "axisA_core_subset.csv")

    # Summary tables
    metric_cols = [
        "test_auc",
        "cv_auc_mean",
        "cv_auc_std",
        "generalization_gap_cv_test_auc",
        "overfit_gap_train_test_auc",
        "test_ap",
        "test_brier",
        "test_ece",
        "n_features",
    ]

    # By A + model + feature_mode
    summary_a_model_mode = summarize_group(
        axis_a_df,
        group_cols=["A", "model", "feature_mode", "run_name"],
        metric_cols=[m for m in metric_cols if m in axis_a_df.columns],
    )
    save_csv(summary_a_model_mode, tables_dir / "summary_axisA_by_model_featuremode.csv")

    # By A only
    summary_a_only = summarize_group(
        axis_a_df,
        group_cols=["A"],
        metric_cols=[m for m in metric_cols if m in axis_a_df.columns],
    )
    save_csv(summary_a_only, tables_dir / "summary_axisA_only.csv")

    # By feature mode
    summary_feature_mode = summarize_group(
        axis_a_df,
        group_cols=["feature_mode"],
        metric_cols=[m for m in metric_cols if m in axis_a_df.columns],
    )
    save_csv(summary_feature_mode, tables_dir / "summary_feature_mode.csv")

    # By model
    summary_model = summarize_group(
        axis_a_df,
        group_cols=["model"],
        metric_cols=[m for m in metric_cols if m in axis_a_df.columns],
    )
    save_csv(summary_model, tables_dir / "summary_model.csv")

    # -------------------------------------------------------------------------
    # 2) Main publication plots
    # -------------------------------------------------------------------------
    # AUC by Axis A
    boxplot_by_category(
        axis_a_df,
        category_col="A",
        value_col="test_auc",
        title="Test ROC AUC by Axis A method",
        ylabel="Test ROC AUC",
        out_path=figs_dir / "fig01_test_auc_by_axisA.png",
        order=AXIS_A_ORDER,
    )

    # Generalization gap by Axis A
    boxplot_by_category(
        axis_a_df,
        category_col="A",
        value_col="generalization_gap_cv_test_auc",
        title="Generalization gap by Axis A method",
        ylabel="CV AUC - Test AUC",
        out_path=figs_dir / "fig02_generalization_gap_by_axisA.png",
        order=AXIS_A_ORDER,
    )

    # CV std by Axis A
    boxplot_by_category(
        axis_a_df,
        category_col="A",
        value_col="cv_auc_std",
        title="Inner-CV AUC variability by Axis A method",
        ylabel="CV AUC std",
        out_path=figs_dir / "fig03_cv_std_by_axisA.png",
        order=AXIS_A_ORDER,
    )

    # AUC by model
    boxplot_by_category(
        axis_a_df,
        category_col="model",
        value_col="test_auc",
        title="Test ROC AUC by model family",
        ylabel="Test ROC AUC",
        out_path=figs_dir / "fig04_test_auc_by_model.png",
        order=MODEL_ORDER,
    )

    # AUC by feature mode
    boxplot_by_category(
        axis_a_df,
        category_col="feature_mode",
        value_col="test_auc",
        title="Test ROC AUC by feature selection regime",
        ylabel="Test ROC AUC",
        out_path=figs_dir / "fig05_test_auc_by_feature_mode.png",
        order=FEATURE_MODE_ORDER,
        figsize=(10, 5),
    )

    # Mean AUC by Axis A
    barplot_mean_with_error(
        axis_a_df,
        category_col="A",
        value_col="test_auc",
        title="Mean Test ROC AUC by Axis A method",
        ylabel="Mean Test ROC AUC",
        out_path=figs_dir / "fig06_mean_auc_by_axisA.png",
        order=AXIS_A_ORDER,
    )

    # -------------------------------------------------------------------------
    # 3) Focused plots for common neutral and full features
    # -------------------------------------------------------------------------
    # Main clean comparison
    neutral_df = axis_a_df.loc[axis_a_df["feature_mode"] == "COMMON_NEUTRAL"].copy()
    if len(neutral_df) > 0:
        boxplot_by_category(
            neutral_df,
            category_col="A",
            value_col="test_auc",
            title="Axis A comparison under COMMON_NEUTRAL",
            ylabel="Test ROC AUC",
            out_path=figs_dir / "fig07_axisA_common_neutral_auc.png",
            order=AXIS_A_ORDER,
        )

    full_df = axis_a_df.loc[axis_a_df["feature_mode"] == "FULL_FEATURES"].copy()
    if len(full_df) > 0:
        boxplot_by_category(
            full_df,
            category_col="A",
            value_col="test_auc",
            title="Axis A comparison under FULL_FEATURES",
            ylabel="Test ROC AUC",
            out_path=figs_dir / "fig08_axisA_full_features_auc.png",
            order=AXIS_A_ORDER,
        )

    # -------------------------------------------------------------------------
    # 4) ComBat effect
    # -------------------------------------------------------------------------
    combat_df = all_df.loc[
        (all_df["B"] == "OFF") &
        (all_df["N"] == "OFF")
    ].copy()

    if len(combat_df) > 0 and "C" in combat_df.columns:
        summary_combat = summarize_group(
            combat_df,
            group_cols=["A", "C", "model", "feature_mode"],
            metric_cols=["test_auc", "cv_auc_mean", "cv_auc_std", "generalization_gap_cv_test_auc"],
        )
        save_csv(summary_combat, tables_dir / "summary_combat_effect.csv")

        boxplot_by_category(
            combat_df,
            category_col="C",
            value_col="test_auc",
            title="Test ROC AUC by ComBat status",
            ylabel="Test ROC AUC",
            out_path=figs_dir / "fig09_auc_by_combat.png",
            order=["OFF", "COMBAT"],
        )

    # -------------------------------------------------------------------------
    # 5) Tables: best runs and best VS/RS/NR/FK
    # -------------------------------------------------------------------------
    top_all = make_top_table(
        all_df,
        sort_cols=["test_auc", "cv_auc_mean", "test_ap"],
        ascending=[False, False, False],
        top_n=30,
    )
    save_csv(top_all, tables_dir / "top30_models_overall.csv")

    best_per_A = (
        all_df.sort_values(["A", "test_auc", "cv_auc_mean", "test_ap"], ascending=[True, False, False, False])
             .groupby("A", as_index=False)
             .head(5)
             .reset_index(drop=True)
    )
    save_csv(best_per_A, tables_dir / "top5_per_axisA.csv")

    # -------------------------------------------------------------------------
    # 6) Compact "article-ready" comparison table
    # -------------------------------------------------------------------------
    article_rows = []
    core_for_article = axis_a_df.copy()

    for A in AXIS_A_ORDER:
        sub = core_for_article.loc[core_for_article["A"] == A].copy()
        if len(sub) == 0:
            continue

        article_rows.append({
            "A": A,
            "n_models": int(len(sub)),
            "test_auc_mean": sub["test_auc"].mean(),
            "test_auc_std": sub["test_auc"].std(),
            "test_auc_median": sub["test_auc"].median(),
            "cv_auc_std_mean": sub["cv_auc_std"].mean() if "cv_auc_std" in sub.columns else np.nan,
            "generalization_gap_mean": sub["generalization_gap_cv_test_auc"].mean() if "generalization_gap_cv_test_auc" in sub.columns else np.nan,
            "overfit_gap_mean": sub["overfit_gap_train_test_auc"].mean() if "overfit_gap_train_test_auc" in sub.columns else np.nan,
            "test_ap_mean": sub["test_ap"].mean() if "test_ap" in sub.columns else np.nan,
            "test_brier_mean": sub["test_brier"].mean() if "test_brier" in sub.columns else np.nan,
            "test_ece_mean": sub["test_ece"].mean() if "test_ece" in sub.columns else np.nan,
        })

    article_table = pd.DataFrame(article_rows)
    save_csv(article_table, tables_dir / "article_ready_axisA_summary.csv")

    # -------------------------------------------------------------------------
    # 7) Best candidate for SHAP follow-up
    # -------------------------------------------------------------------------
    shap_candidates = all_df.copy()
    shap_candidates = shap_candidates.loc[shap_candidates["model"] == "XGB"].copy()
    if len(shap_candidates) > 0:
        best_xgb_per_A = (
            shap_candidates.sort_values(
                ["A", "test_auc", "cv_auc_mean", "test_ap", "generalization_gap_cv_test_auc"],
                ascending=[True, False, False, False, True],
            )
            .groupby("A", as_index=False)
            .head(1)
            .reset_index(drop=True)
        )
        save_csv(best_xgb_per_A, tables_dir / "shap_candidates_best_xgb_per_axisA.csv")

    # -------------------------------------------------------------------------
    # 8) Brief text summary
    # -------------------------------------------------------------------------
    summary_txt = outdir / "summary_interpretation.txt"
    with open(summary_txt, "w", encoding="utf-8") as f:
        f.write("MODEL RUNS SUMMARY\n")
        f.write("=" * 80 + "\n\n")
        f.write(f"Total merged rows: {len(all_df)}\n")
        f.write(f"Unique runs: {all_df['run_name'].nunique()}\n")
        f.write(f"Unique arm-model combinations: {all_df[['run_name','arm_id','model']].drop_duplicates().shape[0]}\n\n")

        if len(article_table) > 0:
            f.write("Axis A compact summary (OFF/OFF/OFF core subset):\n")
            f.write(article_table.to_string(index=False))
            f.write("\n\n")

        if len(top_all) > 0:
            f.write("Top 10 models overall:\n")
            f.write(top_all.head(10).to_string(index=False))
            f.write("\n\n")

        if "VS" in set(all_df["A"].dropna().unique()):
            vs = article_table.loc[article_table["A"] == "VS"]
            if len(vs) > 0:
                f.write("VS summary row:\n")
                f.write(vs.to_string(index=False))
                f.write("\n")

    print(f"[OK] Plots and tables written to: {outdir}")


# =============================================================================
# CLI
# =============================================================================
def build_argparser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(description="Compact post-analysis for modeling.py outputs.")
    p.add_argument(
        "--modelado_dir",
        type=Path,
        default=Path("<REPO_PARENT>/LIDL_lung/study_results/modelado"),
        help="Directory containing modeling run subfolders.",
    )
    p.add_argument(
        "--outdir",
        type=Path,
        default=Path("<REPO_PARENT>/LIDL_lung/study_results/modelado_postanalysis"),
        help="Directory where merged tables and figures will be saved.",
    )
    p.add_argument(
        "--runs",
        nargs="*",
        default=DEFAULT_RUNS,
        help="Run folder names to include. Default includes the 8 recommended runs.",
    )
    return p


def main():
    args = build_argparser().parse_args()
    ensure_dir(args.outdir)

    all_df = load_all_runs(args.modelado_dir, args.runs)
    generate_core_plots(all_df, args.outdir)


if __name__ == "__main__":
    main()

